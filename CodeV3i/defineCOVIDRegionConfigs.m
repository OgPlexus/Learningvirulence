function regions = defineCOVIDRegionConfigs()
% defineCOVIDRegionConfigs  Region list and data files of the SARS-CoV-2 analysis.
%
% CALLS     None
% CALLED BY runCOVID, buildSensitivitySystems
%
% INPUT     none
% OUTPUT
%   regions   1-by-4 struct array with id, label, dataFile (MAT file in the COVID folder that holds the
%             column vectors Mu and Beta of equal length) and periodBreakIndex (first row of the
%             post-mass-vaccination period)
regions = struct( ...
    'id',    {'Global','Europe','Asia','USA'}, ...
    'label', {'Global','Europe','Asia','United States'}, ...
    'dataFile', {fullfile('COVID','Covid19s01092020f08242025.mat'), ...
                 fullfile('COVID','EuropeCovid19s01092020f08242025.mat'), ...
                 fullfile('COVID','AsiaCovid19s01092020f08242025.mat'), ...
                 fullfile('COVID','USACovid19s01092020f05222023.mat')}, ...
    'periodBreakIndex', 451);
end
